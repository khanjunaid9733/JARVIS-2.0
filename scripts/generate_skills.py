SKILL_TEMPLATE = """\
---
name: {skill_id}
description: {description}
---

# {display_name} Skill

## Purpose
{description}

## When to Activate
Activate when the user asks to:
{trigger_list}

## Core Workflows

{workflows}

## Best Practices & Safety Invariants
- Always verify preconditions before initiating actions.
- Log all significant actions to the JARVIS event stream.
- Fail-closed with descriptive error messages on any failure.
- Never expose secrets or credentials in event log payloads.
- Respect user-declared privacy and data minimization principles.
"""


def generate_all_skills(output_dir: Path) -> int:
    total = 0
    for domain_id, domain_name, skills in DOMAINS:
        for skill_id, display_name, description, triggers, workflows in skills:
            skill_dir = output_dir / skill_id
            skill_dir.mkdir(parents=True, exist_ok=True)
            trigger_list = "\n".join(f"- {t}" for t in triggers)
            content = SKILL_TEMPLATE.format(
                skill_id=skill_id,
                display_name=display_name,
                description=description,
                trigger_list=trigger_list,
                workflows=workflows,
            )
